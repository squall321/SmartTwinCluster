#!/bin/bash
################################################################################
# sudo 권한 수동 설정 가이드
# SSH로 접속 가능하지만 sudo 권한이 없는 경우
################################################################################

cat << 'EOF'
================================================================================
🔐 sudo 권한 수동 설정 가이드
================================================================================

문제: SSH 연결은 되지만 sudo 권한이 없는 경우

해결 방법 (각 노드에서 실행):

================================================================================
방법 1: root 계정으로 직접 설정 (권장)
================================================================================

1️⃣  문제가 있는 노드에 로그인:
   ssh node1

2️⃣  root로 전환:
   su -
   # 또는
   sudo su -  # 다른 sudo 권한 있는 계정이 있다면

3️⃣  사용자를 sudo/wheel 그룹에 추가:
   # Ubuntu/Debian:
   usermod -aG sudo koopark
   
   # CentOS/RHEL:
   usermod -aG wheel koopark

4️⃣  sudoers 파일 생성 (패스워드 없이 sudo 사용):
   echo 'koopark ALL=(ALL) NOPASSWD:ALL' > /etc/sudoers.d/koopark
   chmod 0440 /etc/sudoers.d/koopark

5️⃣  검증:
   visudo -c -f /etc/sudoers.d/koopark
   
   # 새 터미널에서 테스트
   ssh node1
   sudo whoami  # "root" 출력되어야 함

================================================================================
방법 2: 다른 sudo 권한 있는 계정 사용
================================================================================

다른 sudo 권한이 있는 계정(예: admin)이 있다면:

ssh admin@node1
sudo usermod -aG sudo koopark
sudo echo 'koopark ALL=(ALL) NOPASSWD:ALL' > /etc/sudoers.d/koopark
sudo chmod 0440 /etc/sudoers.d/koopark

================================================================================
방법 3: 컨트롤러에서 원격 실행
================================================================================

컨트롤러(smarttwincluster)에서 root로 실행:

# node1에 root로 SSH 접속 가능한 경우
ssh root@node1 "usermod -aG sudo koopark && \
  echo 'koopark ALL=(ALL) NOPASSWD:ALL' > /etc/sudoers.d/koopark && \
  chmod 0440 /etc/sudoers.d/koopark"

================================================================================
방법 4: 자동화 스크립트 사용
================================================================================

# Python 스크립트 실행 (root 접근 필요)
python3 setup_sudo_auto.py

================================================================================
✅ 설정 완료 후 테스트
================================================================================

# 각 노드에서 테스트
ssh node1 'sudo whoami'  # "root" 출력되어야 함
ssh node2 'sudo whoami'  # "root" 출력되어야 함

# 또는 검증 스크립트 실행
python3 test_connection.py my_multihead_cluster.yaml

================================================================================
🚨 주의사항
================================================================================

1. root 비밀번호를 모르는 경우:
   - 물리적 접근 또는 콘솔 접근 필요
   - 또는 다른 sudo 권한 있는 계정 필요

2. sudoers 파일 편집시:
   - 반드시 visudo 명령 사용
   - 직접 편집하면 잘못된 문법으로 시스템 잠김 위험

3. 보안:
   - NOPASSWD는 편의성을 위함
   - 프로덕션 환경에서는 패스워드 요구 권장
   - 사용 후 권한 제거 고려

================================================================================
💡 빠른 해결 (모든 노드를 한 번에)
================================================================================

#!/bin/bash
# 컨트롤러에서 root로 실행

for node in node1 node2; do
  echo "Setting up sudo for $node..."
  ssh root@$node "
    usermod -aG sudo koopark || usermod -aG wheel koopark
    echo 'koopark ALL=(ALL) NOPASSWD:ALL' > /etc/sudoers.d/koopark
    chmod 0440 /etc/sudoers.d/koopark
    visudo -c
  "
done

echo "Done! Testing..."
for node in node1 node2; do
  ssh $node 'sudo whoami'
done

================================================================================
EOF
